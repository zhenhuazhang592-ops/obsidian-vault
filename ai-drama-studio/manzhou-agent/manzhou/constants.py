# 情绪跳转矩阵（禁止直接跳转）
EMOTION_TRANSITION_MATRIX = {
    "L1": ["L2", "L3"],           # 平静可跳 L2/L3
    "L2": ["L1", "L3", "L4"],     # 克制可跳 L1/L3/L4
    "L3": ["L2", "L4"],           # 隐忍可跳 L2/L4
    "L4": ["L3", "L5"],           # 爆发可跳 L3/L5
    "L5": ["L4"],                 # 高潮只可跳 L4
}


def is_emotion_jump_allowed(from_level: str, to_level: str) -> bool:
    """校验情绪跳转是否允许"""
    allowed = EMOTION_TRANSITION_MATRIX.get(from_level, [])
    return to_level in allowed


